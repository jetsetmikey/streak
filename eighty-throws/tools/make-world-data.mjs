// Generates src/world-data.js: country outlines (Natural Earth 1:110m via
// world-atlas), friendly country names and flag codes (i18n-iso-countries),
// and the city list with each city's country.
//
//   npm install && npm run data
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import '../src/geo.js';
import CITIES from './cities.mjs';

const require = createRequire(import.meta.url);
const isoCountries = require('i18n-iso-countries');
const here = dirname(fileURLToPath(import.meta.url));
const topology = JSON.parse(readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const geo = globalThis.ET.geo;

// Everyday names where the ISO names are formal or awkward.
const FRIENDLY = {
  US: 'United States', RU: 'Russia', IR: 'Iran', SY: 'Syria', LA: 'Laos', MD: 'Moldova', CZ: 'Czechia',
  MK: 'North Macedonia', TZ: 'Tanzania', TW: 'Taiwan', PS: 'Palestine', FK: 'Falkland Islands', BN: 'Brunei',
  CI: "Côte d'Ivoire", CD: 'DR Congo', CG: 'Republic of the Congo', VE: 'Venezuela', BO: 'Bolivia',
  TF: 'French Southern Lands', BS: 'Bahamas', GM: 'Gambia', KP: 'North Korea', KR: 'South Korea', CN: 'China',
};
// Places in the map data with no ISO number.
const UNCODED = { 'N. Cyprus': ['Northern Cyprus', ''], Somaliland: ['Somaliland', ''], Kosovo: ['Kosovo', 'XK'] };

const geometries = topology.objects.countries.geometries;
const countries = geometries.map((g) => {
  if (!g.id) {
    const [name, a2] = UNCODED[g.properties.name] || [g.properties.name, ''];
    return { name, a2 };
  }
  const a2 = isoCountries.numericToAlpha2(g.id) || '';
  const name = FRIENDLY[a2] || (a2 && isoCountries.getName(a2, 'en')) || g.properties.name;
  return { name, a2 };
});

// Slim the topology down to what the game draws: country shapes and the merged land outline.
const slim = {
  type: 'Topology',
  transform: topology.transform,
  arcs: topology.arcs,
  objects: {
    countries: { type: 'GeometryCollection', geometries: geometries.map((g) => ({ type: g.type, arcs: g.arcs })) },
    land: topology.objects.land,
  },
};

// Find each city's country so labels never name a city across a border.
const world = geo.buildWorld({ topology: slim, countries });
const nudges = [[0, 0], [0.3, 0], [-0.3, 0], [0, 0.3], [0, -0.3]];
const cities = CITIES.map(([name, lat, lon]) => {
  let ci = -1;
  for (const [dy, dx] of nudges) {
    ci = geo.countryAt(world, lat + dy, lon + dx);
    if (ci >= 0) break;
  }
  return [name, lat, lon, ci];
});
const homeless = cities.filter((c) => c[3] < 0).map((c) => c[0]);
const mismatched = cities.filter((c) => c[3] >= 0 && geo.countryAt(world, c[1], c[2]) < 0).map((c) => c[0] + ' → ' + countries[c[3]].name);

const out = `/* Generated by tools/make-world-data.mjs. Do not edit by hand.
 * Country outlines: Natural Earth 1:110m (public domain) via world-atlas.
 * Country names and codes: i18n-iso-countries. */
(function (root) {
  'use strict';
  (root.ET = root.ET || {}).WORLD_DATA = ${JSON.stringify({ topology: slim, countries, cities })};
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
writeFileSync(join(here, '..', 'src', 'world-data.js'), out);
console.log(`src/world-data.js  ${(out.length / 1024).toFixed(1)} KB · ${countries.length} countries · ${cities.length} cities`);
if (homeless.length) console.log(`Cities off the coarse coastline (used for sea landings only): ${homeless.join(', ')}`);
if (mismatched.length) console.log(`Cities nudged onto land: ${mismatched.join(', ')}`);
